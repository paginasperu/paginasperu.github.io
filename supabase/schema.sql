-- Esquema base de Oficial.pe para Supabase. Aplícalo mediante migraciones versionadas.
-- El CSV y la exportación privada de Sheets se importan por separado y se excluyen de Git.

create table if not exists public.locations (
  departamento text not null,
  provincia text not null,
  distrito text not null,
  ubigeo text not null unique,
  primary key (departamento, provincia, distrito)
);

create table if not exists public.profiles (
  id bigint generated by default as identity primary key,
  nombres text not null check (char_length(trim(nombres)) between 2 and 80),
  apellidos text not null check (char_length(trim(apellidos)) between 2 and 100),
  genero text,
  fecha_nacimiento date,
  departamento text not null,
  provincia text not null,
  distrito text not null,
  location_id text not null references public.locations (ubigeo),
  whatsapp_publico text,
  whatsapp_interno text,
  correo text,
  behance_usuario text,
  instagram_usuario text,
  linkedin_usuario text,
  categoria text not null check (categoria in ('Diseñadores gráficos', 'Volanteras', 'Anfitrionas')),
  descripcion_corta text not null,
  descripcion_larga text,
  productos_servicios text,
  nivel_experiencia text,
  nivel_precio text,
  foto_perfil text,
  imagen_portada text,
  acepta_privacidad boolean not null default false,
  calificacion_interna numeric,
  es_verificado boolean not null default false,
  es_destacado boolean not null default false,
  posicion integer,
  estado text not null default 'Pendiente' check (estado in ('Pendiente', 'Activo', 'Rechazado', 'Inactivo')),
  notas text not null default '',
  fecha_registro timestamptz default now(),
  portafolio_url text,
  es_demo boolean not null default false,
  submission_id uuid unique,
  submission_fingerprint text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint profiles_positive_position check (posicion is null or posicion > 0)
);

create unique index if not exists profiles_whatsapp_interno_unique
  on public.profiles (whatsapp_interno);
create index if not exists profiles_location_id_idx
  on public.profiles (location_id);
create index if not exists profiles_public_order_idx
  on public.profiles (posicion nulls last, id)
  where estado = 'Activo';
create index if not exists profiles_status_category_idx
  on public.profiles (estado, categoria, id);

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.registration_rate_limits (
  id bigint generated always as identity primary key,
  contact_hash text not null,
  created_at timestamptz not null default now()
);
create index if not exists registration_rate_limits_contact_time_idx
  on public.registration_rate_limits (contact_hash, created_at desc);

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists profiles_touch_updated_at on public.profiles;
create trigger profiles_touch_updated_at
before update on public.profiles
for each row execute function public.touch_updated_at();

create or replace view public.directory_public_profiles
with (security_invoker = true)
as
select id, nombres, apellidos, departamento, provincia, distrito,
  whatsapp_publico, portafolio_url, instagram_usuario, linkedin_usuario, behance_usuario,
  categoria, descripcion_corta, descripcion_larga, productos_servicios,
  nivel_experiencia, nivel_precio, foto_perfil, imagen_portada,
  es_verificado, es_destacado, posicion, es_demo
from public.profiles
where estado = 'Activo';

alter table public.locations enable row level security;
alter table public.profiles enable row level security;
alter table public.admin_users enable row level security;
alter table public.registration_rate_limits enable row level security;

drop policy if exists "Locations are readable" on public.locations;
create policy "Locations are readable" on public.locations
  for select to anon, authenticated using (true);

drop policy if exists "Active profiles are publicly readable" on public.profiles;
create policy "Active profiles are publicly readable" on public.profiles
  for select to anon using (estado = 'Activo');

drop policy if exists "Admins can read their own membership" on public.admin_users;
create policy "Admins can read their own membership" on public.admin_users
  for select to authenticated using (user_id = (select auth.uid()));

drop policy if exists "Admins can manage profiles" on public.profiles;
create policy "Admins can manage profiles" on public.profiles
  for all to authenticated
  using (exists (select 1 from public.admin_users a where a.user_id = (select auth.uid())))
  with check (exists (select 1 from public.admin_users a where a.user_id = (select auth.uid())));

drop policy if exists "No client access to registration rate limits" on public.registration_rate_limits;
create policy "No client access to registration rate limits" on public.registration_rate_limits
  for all to anon, authenticated using (false) with check (false);

revoke all on public.profiles from anon, authenticated;
revoke all on public.admin_users from anon, authenticated;
revoke all on public.registration_rate_limits from anon, authenticated;
revoke all on public.locations from anon, authenticated;
grant select on public.locations to anon, authenticated;
grant select on public.directory_public_profiles to anon, authenticated;
grant select (id, nombres, apellidos, departamento, provincia, distrito,
  whatsapp_publico, portafolio_url, instagram_usuario, linkedin_usuario, behance_usuario,
  categoria, descripcion_corta, descripcion_larga, productos_servicios,
  nivel_experiencia, nivel_precio, foto_perfil, imagen_portada,
  es_verificado, es_destacado, posicion, es_demo, estado) on public.profiles to anon;
grant select, insert, update, delete on public.profiles to authenticated;
grant select on public.admin_users to authenticated;
grant usage, select on sequence public.profiles_id_seq to authenticated;

-- La Edge Function usa SUPABASE_SERVICE_ROLE_KEY para validar y crear solicitudes.
grant select on public.locations to service_role;
grant select, insert on public.profiles to service_role;
grant select, insert on public.registration_rate_limits to service_role;
grant usage, select on sequence public.profiles_id_seq, public.registration_rate_limits_id_seq to service_role;

